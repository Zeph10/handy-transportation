#!/usr/bin/env node
// Copy core/src into supabase/functions/_shared/core so Edge Functions deploy
// with the exact same logic the browser uses. Run after editing core/:
//   node scripts/sync-core.mjs          (copy)
//   node scripts/sync-core.mjs --check  (CI: fail if the copy is out of date)
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'core', 'src');
const dest = join(root, 'supabase', 'functions', '_shared', 'core');
const header = '// GENERATED by scripts/sync-core.mjs from core/src. Do not edit here.\n';
const check = process.argv.includes('--check');

const files = readdirSync(src).filter((f) => f.endsWith('.ts'));
let stale = [];
if (!check) { rmSync(dest, { recursive: true, force: true }); mkdirSync(dest, { recursive: true }); }
for (const f of files) {
  const content = header + readFileSync(join(src, f), 'utf8');
  const target = join(dest, f);
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== content) stale.push(f);
  } else {
    writeFileSync(target, content);
  }
}
if (check) {
  const extra = existsSync(dest) ? readdirSync(dest).filter((f) => !files.includes(f)) : [];
  if (stale.length || extra.length) {
    console.error(`Edge Function copy of core is out of date (${[...stale, ...extra].join(', ')}). Run: node scripts/sync-core.mjs`);
    process.exit(1);
  }
  console.log('core copy is up to date');
} else {
  console.log(`Copied ${files.length} files to supabase/functions/_shared/core`);
}
